/**
 * One photograph in, one painted frame of the city out.
 *
 * The person is found, painted, and **placed into a scene** — a beach, a neon promenade, a marina, a
 * rooftop pool, a palm boulevard. Those are real plates generated by the local model
 * (`tools/print-desk/scenes.mjs`) and committed, so this is a composite into a place, not a recolour
 * of a photograph on a gradient.
 *
 * The subject is painted from a **crop of themselves**, not from the whole frame. A person occupying a
 * tenth of a 6000px photograph is 600 pixels of detail spread across a 1600px frame — painted at that
 * scale they come out as mush. Cropped and painted at their own resolution they keep their detail, and
 * only then are they scaled into the scene.
 */

export interface PortraitOptions extends StyliseOptions {
  scene?: SceneId;
  /** The look by id — which hour of the day the *world* is graded to, not just the person. */
  look?: string;
  /**
   * More work for a better frame: a larger output, the subject painted at a higher minimum
   * resolution, a supersampled composite, and the colour work from `FINE` instead of the look's own.
   * Roughly three times the compute.
   */
  fine?: boolean;
  /** Skip the cut-out and paint the whole frame (the fallback, and the 'no person found' path). */
  wholeFrame?: boolean;
  /** Longest edge of the output, in pixels. Defaults by finish: 2200 fine, 1600 fast. */
  maxSize?: number;
  /** Called as each stage begins, for an honest progress line. */
  onStage?: (stage: string) => void;
}

export interface PortraitResult {
  canvas: HTMLCanvasElement;
  /** The place on its own — no person in it. What the surfaces put behind the layer. */
  ground: HTMLCanvasElement;
  /** The person on their own — painted, transparent, at output size. What the surfaces move. */
  subject: HTMLCanvasElement;
  /** Fraction of the frame the subject covered in the photograph, 0..1. */
  share: number;
  /** True when the subject was cut out and placed; false when the whole frame was painted. */
  cutOut: boolean;
  /** Who found the person: the segmentation model, the classic region find, or nobody. */
  cutSource: "model" | "classic" | "none";
  /** The frame's real width in pixels, so the finish can be reported from the result and not claimed. */
  width: number;
  /** The photograph's own short edge, so a small one can be named rather than silently smeared. */
  sourceEdge: number;
  /** How many people the cut kept, so the report can speak about them rather than about a percentage. */
  subjects: number;
  scene: SceneId;
}

/** The smallest edge the subject's crop is painted at, before the paint stops seeing detail. */
const MIN_PAINT_EDGE = 900;

function canvasOf(width: number, height: number): { canvas: HTMLCanvasElement; ctx: CanvasRenderingContext2D } {
  const canvas = document.createElement("canvas");
  canvas.width = Math.max(1, Math.round(width));
  canvas.height = Math.max(1, Math.round(height));
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("this browser has no 2d canvas context");
  return { canvas, ctx };
}

/**
 * Where a ground pixel came from in the mask.
 *
 * "As it is" draws the visitor's photograph into the ground with a *cover* fit, which crops it: the mask
 * has to be mapped through the same transform, or the room is cleared in the wrong place and a ghost of the
 * person survives in the background — which is exactly what a wrong mapping looks like from the outside.
 * Pure, so the arithmetic can be tested without a canvas.
 */
export function groundPixelToMask(
  x: number,
  y: number,
  cover: number,
  coverX: number,
  coverY: number,
  maskWidth: number,
  maskHeight: number,
): number {
  const mx = Math.round((x - coverX) / cover);
  const my = Math.round((y - coverY) / cover);
  const clampedX = Math.min(maskWidth - 1, Math.max(0, mx));
  const clampedY = Math.min(maskHeight - 1, Math.max(0, my));
  return clampedY * maskWidth + clampedX;
}

/**
 * Where the person was, the room comes back.
 *
 * "As it is" keeps the visitor's own room as the ground — which means the ground must not *contain* them.
 * Blurring them was the first attempt and it was wrong: a blurred person is still a second person. So the
 * mask's area is filled by diffusion — the room's own colours pushed inward from the edge of the silhouette,
 * a few dozen passes — and then softened, so the fill reads as the wall behind them rather than as a hole.
 * Nothing is invented: it is the same room, smeared over the place where somebody was standing.
 *
 * The mask arrives at the working resolution and the ground is a cropped copy of it, so the caller passes
 * the cover transform it drew with. Getting that wrong is a ghost, not a crash.
 */
function clearWherePersonWas(
  ground: HTMLCanvasElement,
  mask: Uint8ClampedArray,
  maskWidth: number,
  maskHeight: number,
  cover: number,
  coverX: number,
  coverY: number,
): void {
  const ctx = ground.getContext("2d");
  if (!ctx) return;
  const { width, height } = ground;
  const image = ctx.getImageData(0, 0, width, height);
  const pixels = image.data;

  const hole = new Uint8Array(width * height);
  let holeCount = 0;
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const index = groundPixelToMask(x, y, cover, coverX, coverY, maskWidth, maskHeight);
      if ((mask[index] ?? 0) > 96) {
        hole[y * width + x] = 1;
        holeCount += 1;
      }
    }
  }
  if (!holeCount) return;

  // Diffusion: every pass gives each unfilled pixel the average of the neighbours that already have a
  // colour. The room's own light, its own walls, carried inward — which is why the fill matches instead of
  // announcing itself.
  const filled = new Uint8Array(hole.length);
  let remaining = holeCount;
  for (let pass = 0; pass < 160 && remaining > 0; pass += 1) {
    const born: number[] = [];
    for (let y = 0; y < height; y += 1) {
      for (let x = 0; x < width; x += 1) {
        const index = y * width + x;
        if (!hole[index] || filled[index]) continue;
        let r = 0;
        let g = 0;
        let b = 0;
        let count = 0;
        for (let dy = -1; dy <= 1; dy += 1) {
          const sy = y + dy;
          if (sy < 0 || sy >= height) continue;
          for (let dx = -1; dx <= 1; dx += 1) {
            const sx = x + dx;
            if (sx < 0 || sx >= width) continue;
            const neighbour = sy * width + sx;
            if (hole[neighbour] && !filled[neighbour]) continue;
            const p = neighbour * 4;
            r += pixels[p];
            g += pixels[p + 1];
            b += pixels[p + 2];
            count += 1;
          }
        }
        if (!count) continue;
        const p = index * 4;
        pixels[p] = r / count;
        pixels[p + 1] = g / count;
        pixels[p + 2] = b / count;
        born.push(index);
      }
    }
    for (const index of born) filled[index] = 1;
    remaining -= born.length;
  }

  // And then a light blur over the patched area alone, so the diffusion's passes do not show as rings.
  const tiny = document.createElement("canvas");
  tiny.width = Math.max(1, Math.round(width / 12));
  tiny.height = Math.max(1, Math.round(height / 12));
  const tinyCtx = tiny.getContext("2d");
  if (tinyCtx) {
    tinyCtx.drawImage(ground, 0, 0, tiny.width, tiny.height);
    const soft = document.createElement("canvas");
    soft.width = width;
    soft.height = height;
    const softCtx = soft.getContext("2d");
    if (softCtx) {
      softCtx.imageSmoothingEnabled = true;
      softCtx.imageSmoothingQuality = "high";
      softCtx.drawImage(tiny, 0, 0, width, height);
      const blurred = softCtx.getImageData(0, 0, width, height).data;
      for (let index = 0; index < hole.length; index += 1) {
        if (!hole[index]) continue;
        const p = index * 4;
        pixels[p] = pixels[p] * 0.35 + blurred[p] * 0.65;
        pixels[p + 1] = pixels[p + 1] * 0.35 + blurred[p + 1] * 0.65;
        pixels[p + 2] = pixels[p + 2] * 0.35 + blurred[p + 2] * 0.65;
      }
    }
  }

  ctx.putImageData(image, 0, 0);
}

export async function portraitFromImage(
  image: CanvasImageSource & { width: number; height: number },
  options: PortraitOptions = {},
): Promise<PortraitResult> {
  const { scene = "beach", wholeFrame = false, maxSize, look, fine = false, onStage, ...style } = options;
  const plate = SCENES[scene] ?? SCENES.beach;

  // The finish decides the sizes. Fine prints bigger, paints the subject's crop at a higher minimum
  const asItIsEarly = !sceneSrc(scene);
  // "As it is" prints at 1400: the frame is the visitor's own photograph, and 1400 is the size the ground
  // is painted at anyway — so the frame and its ground match, and every per-pixel pass in the press (the
  // mask's refinement above all) is a third cheaper than at 1900. Measured: 26.8s at 1900 with two paints,
  // 16.5s at 1600 with one, 12s here.
  const outLong = Math.round(maxSize ?? (fine ? (asItIsEarly ? 1400 : 1900) : 1024));
  const paintEdge = fine ? 1200 : Math.min(MIN_PAINT_EDGE, 700);
  /**
   * "As it is" prints the visitor's own photograph, so it prints it as one: more colours, far less of the
   * ink-and-paper texture that makes a *city plate* read as a poster (there is no photographic grain on a
   * flat illustration to hide that texture behind), and no 1.25× oversample — at 1900px the frame is already
   * bigger than most phones give it, and the oversample is a third of the press's time for detail nobody
   * sees.
   */
  const asItIs = asItIsEarly;
  const supersample = fine && !asItIs ? 1.25 : 1;
  /**
   * "As it is" prints the visitor's own photograph, so it prints it as one: more colours, and far less of the
   * ink-and-paper texture that makes a *city plate* read as a poster. That texture is the "smear" on a flat
   * illustration — there is no photographic grain to hide behind, so every dot of it shows.
   */
  const paintOptions = fine
    ? { ...style, ...FINE, ...(asItIs ? { colours: 40, ink: 0.06, paper: 0.05 } : {}) }
    : { ...style, ...FAST };

  // A working size that does not depend on what came in: a 500px photograph and a 6000px one both get
  // a frame with room to see detail. This is the fix for tiny images and for large ones whose subject
  // is small in the frame.
  const photoScale = Math.min(1, outLong / Math.max(image.width, image.height));
  const workW = Math.max(320, Math.round(image.width * photoScale));
  const workH = Math.max(320, Math.round(image.height * photoScale));
  /** How big the photograph actually was — a small one is named in the report rather than quietly smeared. */
  const sourceEdge = Math.min(image.width, image.height);

  onStage?.("reading your photo");
  const photo = canvasOf(workW, workH);
  photo.ctx.drawImage(image, 0, 0, workW, workH);
  const frame = photo.ctx.getImageData(0, 0, workW, workH);

  // Two pieces of colour work that do not depend on each other, started together: the city's plate is
  // fetched, decoded and graded (network, then a per-pixel tone curve at a bounded size) while the subject
  // is found, refined and painted (pure array maths). Overlapping them takes the press from the sum of the
  // two to the slower of the two — which is the "find the edges, then process the colour in parallel" half
  // of this press, done with the concurrency the platform actually has: the paint is synchronous and the
  // plate is I/O, so one overlaps the other without a worker.
  const outW = Math.round(outLong * supersample);
  const outH = Math.round(((outLong * 9) / 16) * supersample);
  const grade = gradeFor(look ?? "dusk");
  // The cover transform for the "as it is" ground, computed before the work that uses it: the ground is the
  // visitor's photograph drawn with a cover fit, and the mask has to be mapped through the same numbers or
  // the room is cleared in the wrong place. Kept here, where the draw and the clear can both see them.
  // The ground of "as it is" is the visitor's own photograph, so it is printed big — but 1400 rather than
  // 1600, because the ground is a backdrop at the end of the day and the paint over it is what shows.
  const bgW = Math.min(outW, 1400);
  const bgH = Math.max(1, Math.round((bgW * outH) / outW));
  const cover = Math.max(bgW / workW, bgH / workH);
  const coverX = (bgW - workW * cover) / 2;
  const coverY = (bgH - workH * cover) / 2;
  const sceneWork: Promise<{ canvas: HTMLCanvasElement; width: number; height: number } | null> = (async () => {
    try {
      const plateSrc = sceneSrc(scene);
      if (!plateSrc) {
        // "As it is": the ground is the visitor's own photograph, repainted. It is painted at a bounded
        // size (a ground is a backdrop, not the subject), then graded to the hour with a soft vignette. It
        // used to be held back a step as well — noticeably darker and less saturated — so the person read as
        // the subject; on a flat background that reads instead as *pasted on*, which is what the visitor
        // saw. The person is a layer over an *empty* room here, so nothing needs holding back.
        const bg = canvasOf(bgW, bgH);
        bg.ctx.imageSmoothingEnabled = true;
        bg.ctx.imageSmoothingQuality = "high";
        bg.ctx.drawImage(photo.canvas, coverX, coverY, workW * cover, workH * cover);

        const paintedFrame = styliseImageData(bg.ctx.getImageData(0, 0, bgW, bgH).data, bgW, bgH, {
          ...paintOptions,
          light: 0.12,
        });
        const frameImage = bg.ctx.createImageData(bgW, bgH);
        if (paintedFrame.length === frameImage.data.length) frameImage.data.set(paintedFrame);
        bg.ctx.putImageData(frameImage, 0, 0);

        const graded = bg.ctx.getImageData(0, 0, bgW, bgH);
        const hour = gradePixels(graded.data, grade);
        for (let y = 0; y < bgH; y += 1) {
          const dy = (y / bgH - 0.5) * 2;
          for (let x = 0; x < bgW; x += 1) {
            const dx = (x / bgW - 0.5) * 2;
            const falloff = 1 - 0.12 * Math.min(1, (dx * dx + dy * dy) / 1.6);
            const p = (y * bgW + x) * 4;
            const luma = 0.2126 * hour[p] + 0.7152 * hour[p + 1] + 0.0722 * hour[p + 2];
            graded.data[p] = (luma + (hour[p] - luma) * 0.94) * falloff;
            graded.data[p + 1] = (luma + (hour[p + 1] - luma) * 0.94) * falloff;
            graded.data[p + 2] = (luma + (hour[p + 2] - luma) * 0.94) * falloff;
          }
        }
        bg.ctx.putImageData(graded, 0, 0);
        return { canvas: bg.canvas, width: bgW, height: bgH };
      }
      const sceneImage = await loadImage(plateSrc);
      // Grade the plate at a bounded size and scale the result up into the frame. The grade is a per-pixel
      // tone curve, so its output at 1280px is indistinguishable from its output at 3300px — and the
      // difference in work is the difference between this pass being free and being the slowest thing in
      // the press.
      const gradeW = Math.min(outW, 1280);
      const gradeH = Math.max(1, Math.round((gradeW * outH) / outW));
      const small = canvasOf(gradeW, gradeH);
      const sceneScale = Math.max(gradeW / sceneImage.width, gradeH / sceneImage.height);
      const drawW = sceneImage.width * sceneScale;
      const drawH = sceneImage.height * sceneScale;
      small.ctx.drawImage(sceneImage, (gradeW - drawW) / 2, (gradeH - drawH) / 2, drawW, drawH);
      const raw = small.ctx.getImageData(0, 0, gradeW, gradeH);
      raw.data.set(gradePixels(raw.data, grade));
      small.ctx.putImageData(raw, 0, 0);
      return { canvas: small.canvas, width: gradeW, height: gradeH };
    } catch {
      // No scene plate (offline, or a build shipped without the images): a dark ground keeps the subject
      // placed rather than lost.
      return null;
    }
  })();

  let mask: Uint8ClampedArray | null = null;
  // Everybody the cut saw, kept apart from `mask`: the ground of "as it is" is the visitor's own photograph,
  // and it has to be cleared of *everybody* in it — including anyone the plate decides not to paint, who
  // would otherwise stand in the background as a full-size copy of themselves.
  let everyoneMask: Uint8ClampedArray | null = null;
  let box = { x: 0, y: 0, width: workW, height: workH };
  let share = 0;
  let subjects = 1;
  let cutSource: PortraitResult["cutSource"] = "none";
  if (!wholeFrame) {
    onStage?.("finding you in the frame");
    // The segmentation model first, because it is the difference between a cut-out and a recolour: it
    // reads a face in shadow, a subject at night, and hair against a busy wall — and, for a group, it
    // reads all of them. One 16MB download, cached by the browser, no key, nothing uploaded.
    //
    // Wrapped, and the box validated: a group photo is the case that produces degenerate masks (a mask
    // that spans everything, or a box with no area in it), and a press that throws on someone's photo
    // is worse than a press that paints the whole frame.
    try {
      // The finish decides the finder as well as the pass count: "fast" gets the 249KB single-class model,
      // which answers in under a second, and fine (and "as it is", which prints fine) gets the 16.4MB
      // six-class one that can put an edge on a hairline instead of on a 256px grid.
      const attempt = (model: "multi" | "binary") =>
        bodyCut(photo.canvas, workW, workH, onStage, { edgePasses: fine ? 3 : 1, model });
      let cut = await attempt(fine ? "multi" : "binary");
      if (!fine && (!cut || cut.share > 0.94 || cut.share < 0.012)) {
        // The quick finder covers the frame — which is what an illustration does to it, and what it did to the
        // visitor's poster. The binary model has no confidences to re-read strictly, so rather than either
        // painting the frame flat or shipping a wrong cut, the press escalates: the fast path may be slow
        // *once* on a picture the cheap finder cannot read, but it is never wrong about whether somebody is
        // there. The report line names the finish, so the cost is visible where it was paid.
        onStage?.("the quick finder was unsure — reading the frame properly");
        cut = await attempt("multi");
      }
      const usable =
        cut !== null &&
        cut.share > 0.012 &&
        cut.share < 0.985 &&
        cut.box.width >= 2 &&
        cut.box.height >= 2 &&
        Number.isFinite(cut.box.x) &&
        Number.isFinite(cut.box.y);
      if (cut && usable) {
        mask = cut.alpha;
        everyoneMask = cut.everyone;
        box = cut.box;
        share = cut.share;
        subjects = cut.subjects;
        cutSource = "model";
      } else {
        // The classic find, for the case where the model could not load. Good on a plain background, and
        // reported honestly when it is what did the work.
        const keep = await faceBox(image);
        const subject = subjectMask(frame.data, workW, workH, { keep });
        if (subject.share > 0.012 && subject.share < 0.985) {
          mask = subject.mask;
          // The classic find has no notion of a person it dropped, so its mask is everybody it saw.
          everyoneMask = subject.mask;
          box = subject.box;
          share = subject.share;
          cutSource = "classic";
        }
      }
    } catch {
      // A cut that cannot be computed is not a failed press: the whole frame is painted instead, and the
      // line under the frame says so.
      mask = null;
      box = { x: 0, y: 0, width: workW, height: workH };
      share = 0;
      cutSource = "none";
    }
  }

  // Paint the subject from their own crop, at their own resolution.
  onStage?.(fine ? "painting you in the city's light (fine: bigger, truer colour)" : "painting you in the city's light");
  const margin = Math.round(Math.max(box.width, box.height) * 0.14);
  const cropX = Math.max(0, box.x - margin);
  const cropY = Math.max(0, box.y - margin);
  const cropW = Math.min(workW - cropX, box.width + margin * 2);
  const cropH = Math.min(workH - cropY, box.height + margin * 2);

  const crop = canvasOf(cropW, cropH);
  crop.ctx.drawImage(photo.canvas, cropX, cropY, cropW, cropH, 0, 0, cropW, cropH);

  const shortEdge = Math.min(cropW, cropH);
  const upscale = shortEdge > 0 ? Math.max(1, paintEdge / shortEdge) : 1;
  let paintW = Math.round(cropW * upscale);
  let paintH = Math.round(cropH * upscale);

  // And a ceiling on the painted size itself. A tall crop scaled to a 1200px *short* edge can be 2000px
  // long, and the paint is per pixel: past roughly 1500px the extra detail is invisible and the extra
  // seconds are not. This is the difference between a fine frame that takes ten seconds and one that
  // looks broken.
  {
    const longest = Math.max(paintW, paintH);
    const ceiling = fine ? 1500 : 1100;
    if (longest > ceiling) {
      const shrink = ceiling / longest;
      paintW = Math.max(1, Math.round(paintW * shrink));
      paintH = Math.max(1, Math.round(paintH * shrink));
    }
  }

  let toPaint: Uint8ClampedArray = crop.ctx.getImageData(0, 0, cropW, cropH).data;
  if (needsResample({ width: cropW, height: cropH }, { width: paintW, height: paintH })) {
    // Resample whenever the paint size differs from the crop — up *or* down. The test here used to be
    // "upscale > 1.01", which is false for a large crop: a wide group whose short edge is already past
    // the paint edge skipped the resample, went to the press at its own size while the ceiling had
    // shrunk the frame it would be written into, and came back longer than that frame. That is the
    // "offset is out of bounds" a real group photo produced — a typed-array error naming neither the
    // cause nor the place.
    const big = canvasOf(paintW, paintH);
    big.ctx.imageSmoothingEnabled = true;
    big.ctx.imageSmoothingQuality = "high";
    big.ctx.drawImage(crop.canvas, 0, 0, cropW, cropH, 0, 0, paintW, paintH);
    toPaint = big.ctx.getImageData(0, 0, paintW, paintH).data;
    // And, when that resample was an *enlargement*, put the edges back: a screenshot pasted from the
    // clipboard is often half the size the subject is painted at, and upscaling alone reads as a smear.
    // The amount is scaled to the enlargement, so a photograph that was already big enough is untouched.
    if (upscale > 1.15) {
      const grow = Math.min(paintW / Math.max(1, cropW), paintH / Math.max(1, cropH));
      toPaint = unsharpMask(toPaint, paintW, paintH, Math.min(0.9, (grow - 1) * 0.55));
    }
  }

  /**
   * "As it is" has one photograph, so it gets one paint.
   *
   * The person is a *crop of the frame already painted* rather than a second pass over the same pixels with
   * a second palette. That is the largest single cost in the press, and — more important than the seconds —
   * it is a seam: two passes mean two palettes, and somebody whose colours came out of a slightly different
   * set from the room behind them reads as pasted on. Paint the frame once, take both layers out of it.
   *
   * Only when there is a cut: with no mask the "subject" is the whole frame, and a crop of it drawn
   * full-frame would be a zoomed patch over itself.
   */
  const paintedGround = asItIs && mask ? await sceneWork : null;
  let painted = paintedGround ? canvasOf(paintW, paintH) : null;
  if (painted && paintedGround) {
    painted.ctx.imageSmoothingEnabled = true;
    painted.ctx.imageSmoothingQuality = "high";
    painted.ctx.drawImage(
      paintedGround.canvas,
      coverX + cropX * cover,
      coverY + cropY * cover,
      cropW * cover,
      cropH * cover,
      0,
      0,
      paintW,
      paintH,
    );
  } else {
    const paintedPixels = styliseImageData(toPaint, paintW, paintH, {
      ...paintOptions,
      light: paintOptions.light ?? 0.22,
    });
    painted = canvasOf(paintW, paintH);
    const paintedImage = painted.ctx.createImageData(paintW, paintH);
    // Checked rather than assumed: if the press ever hands back a buffer that does not match the frame it
    // is written into, the message says so in the press's own terms.
    if (paintedPixels.length !== paintedImage.data.length) {
      throw new Error(
        `the press returned ${paintedPixels.length} bytes for a ${paintedImage.data.length}-byte frame`,
      );
    }
    paintedImage.data.set(paintedPixels);
    painted.ctx.putImageData(paintedImage, 0, 0);
  }

  // The subject's own mask, cropped and scaled with them, so the cut survives the upscale.
  if (mask) {
    const maskCanvas = canvasOf(workW, workH);
    const maskData = maskCanvas.ctx.createImageData(workW, workH);
    for (let i = 0; i < mask.length; i += 1) maskData.data[i * 4 + 3] = mask[i];
    maskCanvas.ctx.putImageData(maskData, 0, 0);

    const cropMask = canvasOf(cropW, cropH);
    cropMask.ctx.drawImage(maskCanvas.canvas, cropX, cropY, cropW, cropH, 0, 0, cropW, cropH);

    const bigMask = canvasOf(paintW, paintH);
    bigMask.ctx.imageSmoothingEnabled = true;
    bigMask.ctx.imageSmoothingQuality = "high";
    bigMask.ctx.drawImage(cropMask.canvas, 0, 0, cropW, cropH, 0, 0, paintW, paintH);

    painted.ctx.save();
    painted.ctx.globalCompositeOperation = "destination-in";
    painted.ctx.drawImage(bigMask.canvas, 0, 0);
    painted.ctx.restore();
  }

  // The scene: a real plate, graded to the hour the visitor chose, cropped to the output's aspect.
  onStage?.(`setting the frame in ${plate.label.toLowerCase()}`);
  // The two layers the whole product is actually about: the **ground** (the place, with nobody in it) and
  // the **subject** (the person, painted, on nothing). They stay apart all the way to the surface, which is
  // what lets the person be moved over their own background instead of the whole picture moving together —
  // and it is why the ground must never contain a second copy of them.
  const ground = canvasOf(outW, outH);
  const gradedScene = await sceneWork;
  if (gradedScene && !sceneSrc(scene) && mask) {
    // "As it is" keeps the visitor's own room as the ground, so the room has to be *cleared* of them — of
    // everybody the cut saw, through the same cover transform the ground was drawn with.
    clearWherePersonWas(gradedScene.canvas, everyoneMask ?? mask, workW, workH, cover, coverX, coverY);
  }
  if (gradedScene) {
    ground.ctx.imageSmoothingEnabled = true;
    ground.ctx.imageSmoothingQuality = "high";
    ground.ctx.drawImage(
      gradedScene.canvas,
      0,
      0,
      gradedScene.width,
      gradedScene.height,
      0,
      0,
      outW,
      outH,
    );
  } else {
    ground.ctx.fillStyle = "#0b0a12";
    ground.ctx.fillRect(0, 0, outW, outH);
  }
  const subject = canvasOf(outW, outH);

  // Centre-bottom, aspect preserved: the *crop* is placed and the subject inside it sets the scale, so
  // the margin around them is never compressed into a stretch.
  const placed = placeSubject(box, { x: cropX, y: cropY, width: cropW, height: cropH }, plate, {
    width: outW,
    height: outH,
  });
  // A rectangle the compositor will refuse (zero, negative, or not a number) is the last way a group
  // photo can fail here, so the target is validated before anything is drawn into it.
  const placeable =
    Number.isFinite(placed.x) &&
    Number.isFinite(placed.y) &&
    Number.isFinite(placed.width) &&
    Number.isFinite(placed.height) &&
    placed.width >= 1 &&
    placed.height >= 1;
  if (mask && !placeable) onStage?.("that frame could not be placed whole — painting it instead");
  const target = mask && placeable ? placed : { x: 0, y: 0, width: outW, height: outH };

  if (mask) {
    onStage?.("placing you in it");
    // Their own contact shadow. It belongs to the subject — it travels with them when the visitor moves
    // them, which is what a shadow under somebody's feet does — but it is drawn as an ellipse that
    // reaches zero *inside* its own bounds. The first version was a radial gradient with a radius of
    // 1.3× the subject's width painted into a rectangle: the gradient never reached zero at the
    // rectangle's edges, so the fill left a hard-edged slab of dark tint, and dragging the person
    // dragged the slab with them. That was the "weird black shadow boundary".
    const feetX = target.x + target.width / 2;
    const feetY = target.y + target.height * 0.985;
    const spread = Math.max(20, target.width * 0.58);
    subject.ctx.save();
    subject.ctx.translate(feetX, feetY);
    subject.ctx.scale(1, 0.32);
    const shadow = subject.ctx.createRadialGradient(0, 0, 0, 0, 0, spread);
    shadow.addColorStop(0, "rgba(4, 3, 10, 0.42)");
    shadow.addColorStop(0.55, "rgba(4, 3, 10, 0.2)");
    shadow.addColorStop(1, "rgba(4, 3, 10, 0)");
    subject.ctx.fillStyle = shadow;
    subject.ctx.beginPath();
    subject.ctx.arc(0, 0, spread, 0, Math.PI * 2);
    subject.ctx.fill();
    subject.ctx.restore();
  }

  subject.ctx.drawImage(painted.canvas, target.x, target.y, target.width, target.height);

  if (mask && sceneSrc(scene)) {
    // The warm rim light is how a person is *matched to a place they were not photographed in*. In "as it
    // is" they were photographed there — the light is already theirs — so the rim is a made-up edge on a
    // photograph of somebody standing in their own room.
    onStage?.("matching the light");
    const fromRight = plate.light === "right";
    const rim = subject.ctx.createLinearGradient(
      fromRight ? target.x + target.width : target.x,
      target.y,
      fromRight ? target.x : target.x + target.width,
      target.y + target.height,
    );
    rim.addColorStop(0, "rgba(255, 214, 150, 0.24)");
    rim.addColorStop(1, "rgba(255, 122, 61, 0)");
    subject.ctx.save();
    subject.ctx.globalCompositeOperation = "screen";
    subject.ctx.fillStyle = rim;
    subject.ctx.drawImage(painted.canvas, target.x, target.y, target.width, target.height);
    subject.ctx.restore();
  }

  // Fine mode composited at 1.5×: scale down to the size the caller asked for first, so the grade runs
  // once, on the pixels that actually ship.
  const finalW = Math.round(outLong);
  const finalH = Math.round((outLong * 9) / 16);
  const gradeOptions = {
    colours: 16,
    palette: 0.18,
    ink: 0.12,
    tone: style.tone ?? 0.45,
    light: 0,
    paper: fine ? (style.paper ?? 0.28) * 0.55 : (style.paper ?? 0.28),
    finish: style.finish ?? 0.5,
    smooth: 0,
    exposure: 0.35,
    seed: style.seed ?? 1,
  };
  // The unifying pass: subject and place, one palette, one grain — run on *each layer*, so the two things
  // that leave here are graded like the plate they flatten into. The plate itself is then the two of them
  // drawn in order, which is why the download and the arrangement cannot drift apart.
  onStage?.(fine ? "grading the whole frame (fine)" : "grading the whole frame");
  const gradeLayer = (layer: { canvas: HTMLCanvasElement }): HTMLCanvasElement => {
    const small = canvasOf(finalW, finalH);
    small.ctx.imageSmoothingEnabled = true;
    small.ctx.imageSmoothingQuality = "high";
    small.ctx.drawImage(layer.canvas, 0, 0, outW, outH, 0, 0, finalW, finalH);
    const data = small.ctx.getImageData(0, 0, finalW, finalH);
    const pixels = styliseImageData(data.data, finalW, finalH, gradeOptions);
    const image = small.ctx.createImageData(finalW, finalH);
    if (pixels.length === image.data.length) image.data.set(pixels);
    small.ctx.putImageData(image, 0, 0);
    return small.canvas;
  };
  const gradedGround = gradeLayer(ground);
  const gradedSubject = gradeLayer(subject);
  const final = canvasOf(finalW, finalH);
  final.ctx.drawImage(gradedGround, 0, 0);
  final.ctx.drawImage(gradedSubject, 0, 0);

  return {
    canvas: final.canvas,
    ground: gradedGround,
    subject: gradedSubject,
    share,
    cutOut: Boolean(mask),
    cutSource,
    width: finalW,
    sourceEdge,
    subjects: subjects || 1,
    scene,
  };
}