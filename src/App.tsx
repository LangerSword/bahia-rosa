/**
 * FIRST EDITION — the city's media machine.
 *
 * The shell follows the studio-site language measured in src/index.css: near-black canvas, deep
 * gradient panels, one gold accent, Art Deco display caps over a grotesque text face, and motion that
 * reveals rather than performs. Each stage is a surface, and each surface exposes a different tool set
 * in the editor — that gating is the level design (docs/editor-contract.md).
 */

/**
 * Every tool, on every surface.
 *
 * These used to be gated per surface — a title had no filter, a front page had no stickers — on the theory
 * that each surface should ask for one thing. What that produced was an editor that felt basic: whichever
 * door a visitor came through, the rail was missing something they could see they wanted. The eight tools
 * Unlayer ships (crop, resize, filter, draw, text, shapes, stickers, frame) are all on everywhere now; the
 * *brief* is still per surface, and a brief is not a locked cupboard.
 */
const EVERY_TOOL: ToolGating = {
  crop: true,
  resize: true,
  filter: true,
  draw: true,
  text: true,
  shapes: true,
  stickers: true,
  frame: true,
};
const TITLE_GATING: ToolGating = EVERY_TOOL;
const PAGE_GATING: ToolGating = EVERY_TOOL;
const POSTER_GATING: ToolGating = EVERY_TOOL;

/** Which editor surface a printed style leads into, and what that surface asks for. */
const PLANS: Record<string, { surfaceId: string; title: string; brief: string; gating: ToolGating }> = {
  debut: { surfaceId: "loading", title: "the loading screen", brief: "clean grade, face centred, name plate clear", gating: TITLE_GATING },
  loadingscreen: { surfaceId: "loading", title: "the loading screen", brief: "painted panel — put your name in the clear band along the bottom", gating: TITLE_GATING },
  frontpage: { surfaceId: "frontpage", title: "the front page", brief: "face above the fold, masthead clear, tabloid drama", gating: PAGE_GATING },
  poster: { surfaceId: "poster", title: "the VIP poster", brief: "sell the room; you are the night's draw", gating: POSTER_GATING },
};

type Stage = "gate" | "converting" | "printed" | "printing" | "editing" | "city";

const { locations } = printChoices();

/** The city's own plates — generated by tools/print-desk/scenery.mjs, scenery only, never a person. */
const CITY_ART = {
  boulevard: `${import.meta.env.BASE_URL}art/city/boulevard.jpg`,
  marina: `${import.meta.env.BASE_URL}art/city/marina.jpg`,
  downtown: `${import.meta.env.BASE_URL}art/city/downtown.jpg`,
};

const reveal = { hidden: { opacity: 0, y: 18 }, shown: { opacity: 1, y: 0 } };
const EASE = [0.22, 1, 0.36, 1] as const;

export function App() {
  const [stage, setStage] = useState<Stage>("gate");

  /** The editor is open where there is room for it, and shut on a phone until the visitor asks for it. */
  const [editorOpen, setEditorOpen] = useState(
    typeof window === "undefined" || !window.matchMedia("(max-width: 640px)").matches,
  );

  /**
   * Straight to the city with the press's own plate and the arrangement applied on the way out — the path a
   * phone takes, because the city's four downloads are the product and the editor is a desktop tool.
   */
  const toCity = () => {
    if (!image) return;
    setSaved(image);
    setEdited(false);
    setViaEditor(false);
    setStage("city");
  };

  const [pendingPhoto, setPendingPhoto] = useState<File | null>(null);
  const [choice, setChoice] = useState<PrintChoice>({ surface: "debut", quality: false });
  const [plate, setPlate] = useState<PlateSource | null>(null);
  const [meta, setMeta] = useState<{ register: string; location: string | null; seed: number } | null>(null);
  const [saved, setSaved] = useState<string | null>(null);
  /**
   * Whether the picture in hand came out of the editor.
   *
   * It matters for one thing: an edit is flattened, so the arrangement — the person as a separate layer —
   * no longer exists in it. The arrangement surface is offered until then, and the city says what it is
   * looking at.
   */
  const [edited, setEdited] = useState(false);
  /** The visitor's own photo, kept only so the plate can be shown against it. */
  const [source, setSource] = useState<string | null>(null);
  /** Which of the city's looks the press prints with. */
  const [look, setLook] = useState("dusk");
  /** Which place in the city the frame is set in. */
  const [scene, setScene] = useState<SceneId>("beach");
  /** The stages the press has actually reached, so the progress line is never a lie. */
  const [stages, setStages] = useState<string[]>([]);
  /** What the cut found, reported honestly under the frame. */
  const [cut, setCut] = useState<Pick<PortraitResult, "cutOut" | "share" | "scene" | "cutSource" | "width" | "sourceEdge" | "subjects"> | null>(null);
  const reduce = useReducedMotion();

  /**
   * The title card, played once. `src/lib/entry.ts` holds the decision — a visitor who asked not to be
   * moved, a session that has already watched it, and automation all skip it — and this flag is what the
   * rest of the shell reads: `entered` is false only while the sheet is up, and it holds the hero's own
   * reveal back until the sheet has lifted. A hero that reveals itself behind a covered screen has
   * revealed itself to nobody.
   */
  const [entered, setEntered] = useState(() => !entryShouldPlay(readEntryContext()));

  /** Where the city was entered from, so "back" goes where the visitor actually came from. */
  const [viaEditor, setViaEditor] = useState(false);
  /** Fast, or fine for a slower render with truer colour. */
  const [quality, setQuality] = useState<"fast" | "fine">("fast");
  /** A press that could not read the photo reports itself here, where the photo was chosen. */
  const [pressError, setPressError] = useState<string | null>(null);
  /** And so does a drop or a paste that carried no photo, or more than one. */
  const [intakeProblem, setIntakeProblem] = useState<string | null>(null);
  /**
   * The payoff — the words, the surface, how it sits, and the arrangement — lives here, because two stages
   * use it now: the editing phase sets the arrangement, the city prints it. One store, one state, no way for
   * the two to disagree about a number.
   */
  const payoff = usePayoff("Bahía Rosa", meta?.location ?? null);

  const onSaved = useCallback((dataUrl: string) => {
    setSaved(dataUrl);
    setEdited(true);
    setViaEditor(true);
    setStage("city");
  }, []);
  const image = plate ? (plate.kind === "photo" ? plate.objectUrl : plate.src) : null;
  /**
   * What the editor is handed when the visitor has arranged something.
   *
   * Without this the editor works on the press's own framing, and a Save — with or without an edit — hands
   * the city a picture with the arrangement missing: a visitor would arrange, step into the editor to add
   * one word, save, and find the person back where they started. So the arranged frame is composed here, at
   * the plate's own size, and the editor works on it. Composed *after* the visitor stops moving them (450ms
   * of quiet), because the editor remounts when its image changes and remounting it on every drag frame
   * would throw away their session.
   */
  const [arrangedPlate, setArrangedPlate] = useState<string | null>(null);
  useEffect(() => {
    if (stage !== "editing" || plate?.kind !== "photo" || scene === "asis" || !image) {
      setArrangedPlate(null);
      return;
    }
    // Nothing arranged (and nothing changed about how it sits): the press's own plate already is this
    // arrangement, so there is nothing to compose and no remount to pay for.
    if (isDefaultLayer(payoff.layer) && payoff.fit === "contain") {
      setArrangedPlate(null);
      return;
    }
    let cancelled = false;
    let made: string | null = null;
    const timer = window.setTimeout(() => {
      void (async () => {
        try {
          const blob = await composePlacement({
            placement: FRAME,
            artworkUrl: plate.groundUrl ?? image,
            subjectUrl: plate.subjectUrl,
            copy: payoff.copy,
            fit: payoff.fit,
            layer: payoff.layer,
          });
          if (cancelled) return;
          made = URL.createObjectURL(blob);
          setArrangedPlate(made);
        } catch {
          // A compose that fails leaves the editor on the press's own plate — the situation before this
          // effect existed, and not a reason to hold up the editor.
          if (!cancelled) setArrangedPlate(null);
        }
      })();
    }, 450);
    return () => {
      cancelled = true;
      window.clearTimeout(timer);
      if (made) URL.revokeObjectURL(made);
    };
  }, [stage, plate, image, scene, payoff.layer, payoff.fit, payoff.copy]);
  /** The download's own filename: from the photo's name where there is one, without any text burned in. */
  const frameName = `bahia-rosa-${
    plate && "name" in plate && plate.name ? String(plate.name).replace(/\.[^.]+$/, "") : "frame"
  }.png`;
  const plan = PLANS[choice.surface] ?? PLANS.debut;

  const printed = useCallback(
    (next: PlateSource, printedMeta: { register: string; location: string | null; seed: number }) => {
      setPlate(next);
      setMeta(printedMeta);
      toast.show({
        tone: "success",
        title: "the desk printed it",
        description: "the plate came back from the local model — no key, no upload",
      });
      // The plate goes to the fork, not straight into the editor: download it raw, or take it in and
      // make something. The visitor chooses, both are one click.
      setStage("printed");
    },
    [],
  );

  /**
   * The default press: the city's look, in this browser, with no model and nothing uploaded. A photo
   * becomes flat paint with ink over it in a second or two on a phone, which is what makes the
   * platform work for everyone — the desk (a real diffusion model on a GPU) stays as the upgrade.
   */
  const press = useCallback(
    async (file: File) => {
      // Capture the run: if the visitor leaves before this finishes, the result is dropped.
      const token = runToken.current;
      setStages([]);
      setPressError(null);
      setStage("converting");
      const url = URL.createObjectURL(file);
      try {
        const image = await loadImage(url);
        const preset = LOOKS[look]?.options ?? LOOKS.dusk.options;
        const result = await portraitFromImage(image, {
          ...preset,
          scene,
          look,
          // "As it is" is the visitor's own photograph, printed as it is: no cut, no separation, no layers —
          // the whole frame, repainted and graded. It prints at the fine finish whatever finish was chosen
          // for a city plate, because the frame they keep is the frame they gave, and it pays for no model:
          // `wholeFrame` means the segmentation never runs.
          wholeFrame: scene === "asis",
          fine: quality === "fine" || scene === "asis",
          seed: 1 + (file.size % 997),
          onStage: (label) => setStages((seen) => (seen.includes(label) ? seen : [...seen, label])),
        });
        if (token !== runToken.current) {
          URL.revokeObjectURL(url);
          return;
        }
        setCut({
          cutOut: result.cutOut,
          share: result.share,
          scene: result.scene,
          cutSource: result.cutSource,
          width: result.width,
          sourceEdge: result.sourceEdge,
          subjects: result.subjects,
        });
        setPlate({
          kind: "photo",
          objectUrl: result.canvas.toDataURL("image/jpeg", 0.94),
          name: file.name,
          // The two layers, kept apart all the way to the surfaces: the place without the person, and the
          // person on their own. The plate above is the two of them flattened, for the raw download.
          groundUrl: result.ground.toDataURL("image/jpeg", 0.92),
          subjectUrl: result.subject.toDataURL("image/png"),
        });
        setSource(url); // kept for the before/after comparison; revoked on reset
        setMeta(null);
        toast.show({
          tone: "success",
          title: "the plate is ready",
          description: `${SCENES[result.scene].label} · ${quality === "fine" || scene === "asis" ? "fine" : "fast"} · printed in this tab`,
        });
        setStage("printed");
        // The condition that this press just fixed is no longer true, so it leaves the stack with it.
        dismissAlert("press-failure");
      } catch (failure) {
        if (token !== runToken.current) {
          URL.revokeObjectURL(url);
          return;
        }
        // A failure here used to send the visitor to the desk screen — ComfyUI on a machine that does not
        // exist for anyone on the deployed site — which is how a group photo ended up staring at "no
        // print desk is running". The desk is an opt-in this page was pointed at: with none, the press
        // reports itself where the photo was chosen, with the reason attached.
        URL.revokeObjectURL(url);
        if (deskRoot()) {
          setPendingPhoto(file);
          setStage("printing");
          return;
        }
        setPressError(failure instanceof Error ? failure.message : "the press could not read that photo");
        // A refusal is a condition, not a moment: it waits in the stack until the visitor dismisses it or a
        // later press succeeds. One stable id, so a second failure replaces the first instead of stacking.
        pushAlert({
          id: "press-failure",
          tone: "stop",
          title: "That photograph could not be pressed",
          detail: failure instanceof Error ? failure.message : undefined,
        });
        setStage("gate");
      }
    },
    [scene, look, quality],
  );

  /**
   * One door for every way a photograph arrives: the picker, a drop anywhere on the page, a paste.
   *
   * Three entrances and one behaviour, because the alternative is three subtly different behaviours —
   * which is how a paste ends up not saving the payoff that a click does.
   */
  const takePhoto = useCallback(
    (file: File) => {
      setIntakeProblem(null);
      setPressError(null);
      // The press decides the print: the desk keeps its own defaults, and the visitor's only choices are
      // the place and the hour, which live on the sections above.
      setChoice({ surface: "debut", quality: false });
      if (deskRoot()) {
        // This page was pointed at a desk on purpose (?desk=…), so print there, with the model.
        setPendingPhoto(file);
        setStage("printing");
        return;
      }
      void press(file);
    },
    [press],
  );

  const useFallback = useCallback(() => {
    // The payoff stage needs an artwork and the deployed build has no GPU: the city's own plate is
    // the honest stand-in — scenery, no person, nothing borrowed.
    setSaved(CITY_ART.marina);
    setMeta(null);
    setViaEditor(false);
    setStage("city");
  }, []);

  /**
   * Back to the start, from anywhere — including *during* a press.
   *
   * Two things this has to get right, and did not:
   *
   *   1. A press still running must not land after the visitor has walked away. The press carries this
   *      token; the reset bumps it, and a result from an older token is dropped instead of pulling them
   *      forward into a stage they left.
   *   2. The intake does not exist at click time — the gate stage renders it — so the browser has
   *      nothing to scroll to when it follows `#intake`, and the first click did nothing at all. The
   *      scroll happens here instead, after React has rendered the stage.
   */
  const runToken = useRef(0);
  const reset = useCallback(() => {    runToken.current += 1;
    setPlate(null);
    setPendingPhoto(null);
    setSaved(null);
    setEdited(false);
    setMeta(null);
    setStage("gate");
    if (source) URL.revokeObjectURL(source);
    setSource(null);
    window.setTimeout(() => {
      const node = document.getElementById("intake");
      if (!node) return;
      node.scrollIntoView({ behavior: reduce ? "auto" : "smooth", block: "start" });
      node.focus({ preventScroll: true });
    }, 0);
  }, [source, reduce]);
  // ?demo=launch — the tour without the model. The deployed build has no GPU, so a visitor (or a
  // judge) who cannot run the desk still gets to see the payoff: the city's own plate, launched into
  // the city. Same components, same exporter; only the artwork's provenance changes.
  useEffect(() => {
    const demo = new URLSearchParams(window.location.search).get("demo");
    if (demo === "launch") {
      useFallback();
      return;
    }
    // The editor without a GPU: the city's own plate stands in as the artwork, so the React Image
    // Editor surface (and its gating) can be seen, driven and tested on any machine.
    if (demo === "editor") {
      setPlate({ kind: "plate", id: "city-downtown", src: CITY_ART.downtown });
      setMeta(null);
      setStage("editing");
    }
  }, [useFallback]);

  // Two steps, because that is what the product is: you get a plate, and the city runs it. The
  // editor is a detour inside the first step, not a stage of its own — which is why the payoff can be
  // reached without it.
  const stepIndex = stage === "city" ? 1 : 0;
  const steps = [
    { label: "Your plate", hint: "a photo, and what the city makes of it" },
    { label: "The city", hint: "billboard · foyer · feed · postcard" },
  ];

  // A stage that changes silently leaves a keyboard or screen-reader visitor at the top of the page with
  // no idea anything happened. Move the view to the work, and put focus there, so tabbing continues from
  // where the new thing is.
  useEffect(() => {
    if (stage === "gate") return;
    const node = document.getElementById("stage");
    if (!node) return;
    node.scrollIntoView({ behavior: reduce ? "auto" : "smooth", block: "start" });
    node.focus({ preventScroll: true });
  }, [stage, reduce]);

  /**
   * One way home, from every place that offers it.
   *
   * The hero's own "Bring a photo" was a bare `#intake` anchor, and the intake only exists once the
   * gate stage renders it — so on any other stage the click had nothing to scroll to and did nothing.
   * Every route home now goes through here: prevent the hash jump, reset, then scroll once React has
   * rendered the stage. The href stays on the elements for the keyboard and for a copied link.
   */
  const goHome = useCallback(
    (event: ReactMouseEvent) => {
      event.preventDefault();
      reset();
    },
    [reset],
  );

  /** What the finish actually produced — read from the result, so it cannot be a claim. */
  // The finish in the report is the finish that *ran*, not the one the control says: "as it is" always
  // prints at the fine finish, so the line must not claim "fast" beside a 1900px frame.
  const cutLabel = `${quality === "fine" || scene === "asis" ? "fine" : "fast"} · ${cut?.width ?? 0}px wide`;

  /**
   * What the cut did, in the city's voice rather than as a readout.
   *
   * The count and the share are still doing the work — they decide which line is true — but a visitor wants
   * to know how the frame sees them, not what percentage of it they occupy. So the number is spent on
   * choosing a phrase instead of being printed.
   */
  /**
   * How the frame sees them, in words.
   *
   * One region is read as "you". More than one is read as "the group" and *not* as a number: people who
   * stand close together merge into a single region, so the count of regions is a floor and never a count —
   * saying "the two of you" over four merged people is worse than saying nothing, because it is wrong in a
   * way the visitor can see.
   */
  const who = cut?.cutSource === "model" && cut.subjects > 1 ? "the group" : "you";
  const presence =
    scene === "asis"
      ? "the whole frame, printed as it is"
      : cut?.cutSource === "model"
      ? cut.share > 0.45
        ? `${who}, filling the frame`
        : cut.share > 0.22
          ? `${who}, close to the lens`
          : cut.share > 0.09
            ? `${who}, a little way off`
            : `${who}, small in a wide frame`
      : cut?.cutSource === "classic"
        ? "the rough find did the cut — the segmenter could not load"
        : meta
          ? "printed at the desk"
          : cut
            ? "no one could be told apart from the room, so the whole frame was painted"
            : "";
  const cutLine = [
    presence,
    cut ? cutLabel : "",
    // A small photograph is named rather than quietly smeared: a pasted screenshot is often half the size
    // the subject is painted at, and the honest advice is a bigger copy.
    cut && cut.sourceEdge < 900
      ? `from a ${cut.sourceEdge}px photo${cut.sourceEdge < 640 ? " — a bigger copy will press sharper" : ""}`
      : "",
  ]
    .filter(Boolean)
    .join(" · ");

  return (
    <div className="grain vignette min-h-screen">
      <Fx />
      <Toasts />
      <Alerts />
      <MagneticCursor busy={stage === "converting" || stage === "printing"} />
      {entered ? null : <Entry onDone={() => setEntered(true)} />}
      <a href="#intake" className="skip">
        Skip to the press
      </a>

      <header className="masthead rule sticky top-0 z-20 border-b">
        <div className="mx-auto max-w-[1280px] px-4 sm:px-8">
          <div className="flex flex-wrap items-baseline justify-between gap-x-6 gap-y-1 py-3 sm:py-4">
            <div className="flex items-baseline gap-4">
              <a
                href="#intake"
                data-testid="home"
                onClick={goHome}
                className="wordmark text-2xl leading-none sm:text-3xl"
                aria-label="Bahía Rosa — back to the start"
              >
                Bahía Rosa
              </a>
              <span className="kicker hidden sm:inline">la gaviota · the coast edition</span>
            </div>
            <div className="flex items-center gap-6">
              <a
                href="#intake"
                data-testid="bring-a-photo"
                onClick={goHome}
                className="fx-link text-xs"
                style={{ color: "var(--color-muted)" }}
              >
                bring a photo
              </a>
              <span className="kicker hidden md:inline">{locations.length} places</span>
              <span className="kicker hidden sm:inline" style={{ color: "var(--color-flag)" }}>
                {deskRoot() ? "printing at the desk" : "printing in your browser"}
              </span>
            </div>
          </div>
          <div className="nameplate-rule" aria-hidden="true" />
          <nav className="steprail py-3" aria-label="The run">
            {steps.map((step, index) => (
              <span
                key={step.label}
                className="step"
                data-state={index === stepIndex ? "now" : index < stepIndex ? "done" : "todo"}
                aria-current={index === stepIndex ? "step" : undefined}
              >
                {index > 0 ? <span style={{ color: "var(--color-faint)" }}>·</span> : null}
                {step.label.toLowerCase()}
                {index === stepIndex ? (
                  // One ink mark, shared between steps: motion moves it along the rail rather than drawing a
                  // new one at each stop, so the run reads as a single object travelling through the paper.
                  <motion.span
                    layoutId="step-ink"
                    className="step-ink"
                    aria-hidden="true"
                    transition={{ duration: reduce ? 0 : 0.42, ease: EASE }}
                  />
                ) : null}
              </span>
            ))}
          </nav>
        </div>
      </header>

      {/* A photo from anywhere: dropped on the page, or pasted. Live on every stage where a new photo is a
          sensible thing to want — which is every stage except the editor, where a drop belongs to the
          editor's own canvas. Being picky about the stage is what made a drop do nothing at all on the city,
          which is exactly where someone with an arrangement in front of them tries it. */}
      <PhotoDrop
        enabled={stage !== "editing"}
        hasWork={Boolean(plate || cut || saved || stage !== "gate")}
        onPhoto={takePhoto}
        onProblem={setIntakeProblem}
      />

      <main className="mx-auto max-w-[1280px] px-4 sm:px-8">
        <motion.section
          initial={reduce ? undefined : "hidden"}
          animate={reduce ? undefined : entered ? "shown" : "hidden"}
          variants={reveal}
          transition={{ duration: 0.7, ease: EASE }}
          data-testid="hero"
          className="rule relative mt-8 overflow-hidden border"
        >
          <HeroParallax>
            <Hero3D
              scene={scene}
              look={look}
              className="hero-depth hero-depth-far absolute inset-0 h-full w-full"
            />
            <div className="city-scrim" aria-hidden="true" />
            <div className="relative px-6 py-14 sm:px-10 sm:py-20">
              <div className="hero-depth hero-depth-mid">
                <h1 className="display mt-5 text-4xl sm:text-5xl">Bahía Rosa</h1>
                <p className="deck mt-7">One photo. The city paints it, then runs it.</p>
              </div>

              <div className="hero-depth hero-depth-near mt-9 flex flex-wrap items-center gap-3">
                <a
                  href="#intake"
                  data-magnet="hero-door"
                  data-testid="hero-cta"
                  onClick={goHome}
                  className="lift border px-6 py-3 text-xs tracking-[0.2em] uppercase"
                  style={{ background: "var(--color-gold)", color: "var(--color-ink)", borderColor: "var(--color-gold)" }}
                >
                  Bring a photo
                </a>
                <span className="text-xs" style={{ color: "var(--color-muted)" }}>
                  no account · no upload · nothing leaves this page
                </span>
              </div>

            </div>
          </HeroParallax>
        </motion.section>

        <div className="mt-8">
          <Marquee items={locations.map((place) => place.label)} />
        </div>

        {stage === "gate" ? (
          <motion.div
            initial={reduce ? undefined : "hidden"}
            whileInView={reduce ? undefined : "shown"}
            viewport={{ once: true, margin: "-80px" }}
            variants={reveal}
            transition={{ duration: 0.6, ease: EASE }}
            id="intake"
            style={{ scrollMarginTop: "7.5rem" }}
            className="mt-10"
          >
            {/* The station's subject, at size. The hour and the place are choices about *this* plate, and a
                208px thumbnail asks the visitor to imagine the answer. It is the press's own code drawing it,
                so the preview and the print cannot disagree. */}
            <div className="section-tight" data-testid="pick-preview">
              <div
                className="border p-2"
                style={{ borderColor: "rgb(242 239 233 / 18%)", background: "var(--color-ink-2, #101014)" }}
              >
                <SceneThumb
                  scene={scene}
                  look={look}
                  width={720}
                  height={405}
                  className="w-full"
                  testId="pick-preview-canvas"
                />
              </div>
              <p className="mt-4" style={{ color: "var(--color-muted)" }}>
                <span className="text-sm" style={{ color: "var(--color-paper)" }}>
                  {SCENES[scene].label.toLowerCase()}
                </span>
                <span className="text-sm"> at </span>
                <span className="text-sm" style={{ color: "var(--color-gold)" }}>
                  {LOOKS[look]?.label.toLowerCase()}
                </span>
                <span className="mt-1 block text-xs">
                  the two rows below change this plate. it is drawn by the press itself — the same code that
                  will print your photograph.
                </span>
              </p>
            </div>

            <section className="section-tight" aria-labelledby="hour-heading">
              <h2 id="hour-heading" className="display" style={{ color: "var(--color-paper)" }}>
                <span style={{ color: "var(--color-faint)" }}>~ </span>the hour
              </h2>
              <p className="measure mt-2 text-xs" style={{ color: "var(--color-muted)" }}>
                four hours, every one of them shown on the same place — the beach — so they can be compared
                against each other. the hour grades the whole plate: its sky, its water, its asphalt, not only
                the person standing in it.
              </p>
              <div
                className="mt-4 grid grid-cols-2 gap-3 sm:flex sm:flex-wrap"
                role="group"
                aria-label="The hour"
              >
                {Object.entries(LOOKS).map(([id, preset], index) => (
                  <Tile
                    key={id}
                    dots="hour"
                    index={index}
                    active={id === look}
                    testId={`look-${id}`}
                    onClick={() => setLook(id)}
                    label={preset.label.toLowerCase()}
                    note={preset.blurb}
                    /* One fixed place for the whole row. A thumbnail that re-renders when the *other* row
                       changes is a strip you cannot compare, because the thing you are comparing moves. */
                    media={<SceneThumb scene="beach" look={id} className="w-full sm:w-[220px]" />}
                  />
                ))}
              </div>
            </section>
            <section className="section-tight" aria-labelledby="place-heading">
              <h2 id="place-heading" className="display" style={{ color: "var(--color-paper)" }}>
                <span style={{ color: "var(--color-faint)" }}>~ </span>the place
              </h2>
              <p className="measure mt-2 text-xs" style={{ color: "var(--color-muted)" }}>
                the places the press prints into, every one of them shown at your hour — pick a place here and
                the plate above changes to it; pick an hour above and the thumbnails here come to you at that
                light. “as it is” is no place at all: your photograph, on its own.
              </p>
              <div
                className="mt-4 grid grid-cols-2 gap-3 sm:flex sm:flex-wrap"
                role="group"
                aria-label="The place"
              >
                {SCENE_IDS.map((id, index) => (
                  <Tile
                    key={id}
                    dots="place"
                    index={index}
                    active={id === scene}
                    testId={`scene-${id}`}
                    onClick={() => setScene(id)}
                    label={SCENES[id].label.toLowerCase()}
                    note={SCENES[id].blurb}
                    /* The whole row follows the hour, and no thumbnail for “as it is”: it has no scene to
                       show, and a blank frame among four drawings reads as the broken one. Clicking an hour
                       up top brings every place down here to that light — the comparison moves with the
                       choice, which is the point of choosing. */
                    media={
                      id === "asis" ? undefined : (
                        <SceneThumb scene={id} look={look} className="w-full sm:w-[220px]" />
                      )
                    }
                  />
                ))}
              </div>
            </section>
            <section className="section-tight" aria-labelledby="finish-heading">
              <h2 id="finish-heading" className="display" style={{ color: "var(--color-paper)" }}>
                <span style={{ color: "var(--color-faint)" }}>~ </span>the finish
              </h2>
              <p className="measure mt-2 text-xs" id="finish-note" style={{ color: "var(--color-muted)" }}>
                fast: seconds. fine: bigger, truer colour, slower.
              </p>
              <div
                className="mt-4 grid grid-cols-2 gap-3 sm:flex sm:flex-wrap"
                role="radiogroup"
                aria-labelledby="finish-heading"
                aria-describedby="finish-note"
              >
                {(
                  [
                    ["fast", "fast", "20 colours · a few seconds"],
                    ["fine", "fine", "32 colours · slower, truer colour"],
                  ] as const
                ).map(([id, label, hint], index) => (
                  <Tile
                    key={id}
                    dots="finish"
                    index={index}
                    role="radio"
                    active={quality === id}
                    testId={`finish-${id}`}
                    onClick={() => setQuality(id)}
                    label={label}
                    note={hint}
                    media={
                      /* The two finishes differ by how much frame they print, so the tile says so in pixels
                         rather than in adjectives: bars to the same scale, labelled with the real widths. */
                      <span className="tile-scale" aria-hidden="true">
                        <span
                          className="tile-scale-bar"
                          style={{ width: id === "fast" ? "67%" : "100%" }}
                        />
                        <span className="tile-scale-label">
                          {id === "fast" ? "1280px frame" : "1900px frame"}
                        </span>
                      </span>
                    }
                  />
                ))}
              </div>
            </section>
            {pressError ? (
              <p
                data-testid="press-error"
                role="status"
                className="measure mt-6 text-xs"
                style={{ color: "var(--color-danger)" }}
              >
                that photo could not be pressed — {pressError}. another one, or a smaller file, will work.
              </p>
            ) : null}
            {intakeProblem ? (
              <p
                data-testid="intake-problem"
                role="status"
                className="measure mt-3 text-xs"
                style={{ color: "var(--color-danger)" }}
              >
                {intakeProblem}
              </p>
            ) : null}
            <PlateGate onPhoto={takePhoto} />

            {/* The proof, after the pitch: the press's own plates, once the choices are made — the gallery
                is what the picker above produces, so it reads as evidence rather than decoration. */}
            <PlateGallery />
          </motion.div>
        ) : null}

        <div id="stage" tabIndex={-1} style={{ scrollMarginTop: "7.5rem" }} className="outline-none">
        <p className="sr-only" role="status" data-testid="stage-status">
          step {stepIndex + 1} of {steps.length}: {steps[stepIndex].label}
        </p>

        {stage === "converting" ? (
          <motion.section
            initial={reduce ? undefined : "hidden"}
            animate={reduce ? undefined : "shown"}
            variants={reveal}
            transition={{ duration: 0.5, ease: EASE }}
            className="panel rule mt-10 border p-8"
            data-testid="converting"
          >
            <p className="kicker">Step 1 · The press</p>
            <h2 className="display mt-3 text-4xl">Printing you into the city</h2>
            <p className="mt-3 max-w-[62ch] text-sm leading-relaxed text-[color:var(--color-muted)]">
              Everything below happens inside this page. Your photo is not uploaded anywhere, and there
              is no key or account in the path.
            </p>
            {/* Each stage is stamped onto the list as it finishes, the way a press stamps a sheet: quickly,
                with a little weight, and no bounce — it is a receipt, not a celebration. */}
            <ol className="mt-6 space-y-2" aria-live="polite">
              {stages.map((label) => (
                <motion.li
                  key={label}
                  className="flex items-baseline gap-3 text-sm text-[color:var(--color-body)]"
                  initial={reduce ? undefined : { opacity: 0, scale: 1.16, rotate: -1.5 }}
                  animate={reduce ? undefined : { opacity: 1, scale: 1, rotate: 0 }}
                  transition={{ duration: 0.24, ease: EASE }}
                >
                  <span style={{ color: "var(--color-gold)" }}>✓</span>
                  {label}
                </motion.li>
              ))}
            </ol>
            <div className="rule mt-6 h-[3px] w-full overflow-hidden border" aria-hidden="true">
              <motion.div
                className="h-full"
                style={{ background: "var(--color-gold)" }}
                initial={{ width: "6%" }}
                animate={{ width: `${Math.min(94, 18 + stages.length * 19)}%` }}
                transition={{ duration: 0.45, ease: EASE }}
              />
            </div>
            <PressTips />
          </motion.section>
        ) : null}

        {stage === "printed" && image ? (
          <motion.section
            initial={reduce ? undefined : { opacity: 0, y: 14 }}
            animate={reduce ? undefined : { opacity: 1, y: 0 }}
            transition={{ duration: 0.5, ease: EASE }}
            className="panel rule mt-10 border p-8"
            data-testid="printed-fork"
          >
            <h2 className="display mt-3 text-4xl">
              There you are, in {SCENES[cut?.scene ?? scene].label.toLowerCase()}
            </h2>
            <p className="measure mt-3 text-xs" style={{ color: "var(--color-muted)" }} data-testid="cut-line">
              {cutLine}
            </p>

            <div className="mt-7 grid gap-7 lg:grid-cols-[minmax(0,1fr)_320px]">
              <div className="rule overflow-hidden border">
                {/* The press is over. The card turns over — after the press, not during it — and hands over
                    the art: the spin is the reveal, and the print is what is left when it stops. */}
                <CardReveal plate={image}>
                  <img
                    src={image}
                    alt="Your plate, freshly printed"
                    data-testid="printed-plate"
                    className="w-full"
                  />
                </CardReveal>
              </div>
              <div className="flex flex-col gap-3">
                <a
                  href={image}
                  download={frameName}
                  data-testid="download-raw"
                  className="btn text-center"
                  onClick={() =>
                    toast.show({
                      tone: "success",
                      title: "downloaded",
                      description: `${frameName} — clean, no text, no watermark`,
                    })
                  }
                >
                  Download it raw
                </a>
                <span className="text-xs" style={{ color: "var(--color-faint)" }}>
                  clean PNG · no text, no watermark
                </span>
                <button
                  type="button"
                  data-testid="take-to-city"
                  onClick={() => {
                    setSaved(image);
                    setEdited(false);
                    setViaEditor(false);
                    setStage("city");
                  }}
                  className="btn-quiet text-center"
                >
                  Take it into the city
                </button>
                <span className="text-xs" style={{ color: "var(--color-faint)" }}>
                  the billboard · the foyer · the feed · the postcard — straight there, no editing needed
                </span>
                <button
                  type="button"
                  data-testid="edit-in-editor"
                  onClick={() => setStage("editing")}
                  className="btn-quiet text-center"
                >
                  Open the editor instead
                </button>
                <span className="text-xs" style={{ color: "var(--color-faint)" }}>
                  text · filters · crop · drawing · shapes · stickers
                </span>
                <button
                  type="button"
                  onClick={reset}
                  className="fx-link mt-3 text-left text-xs tracking-[0.2em] text-[color:var(--color-faint)] uppercase hover:text-[color:var(--color-gold)]"
                >
                  Bring a different photo
                </button>
              </div>
            </div>

            {source && image ? (
              <div className="mt-7">
                <BeforeAfter before={source} after={image} />
              </div>
            ) : null}
          </motion.section>
        ) : null}

        {stage === "printing" && pendingPhoto ? (
          <div className="mt-10">
            <PrintDesk file={pendingPhoto} choice={choice} onPrinted={printed} />
          </div>
        ) : null}

        {stage === "editing" && image ? (
          <motion.section
            initial={reduce ? undefined : { opacity: 0, y: 14 }}
            animate={reduce ? undefined : { opacity: 1, y: 0 }}
            transition={{ duration: 0.5, ease: EASE }}
            className="editor-shell panel rule mt-10 border p-4 sm:p-8"
            data-testid="editor-shell"
          >
            <div className="rule mb-5 flex flex-col items-start gap-3 border-b pb-4 sm:flex-row sm:items-center sm:justify-between">
              <div>
                <h2 className="display text-2xl sm:text-3xl">{plan.title}</h2>
              </div>
              <button
                type="button"
                data-testid="start-over"
                onClick={reset}
                className="lift rule flex min-h-11 items-center border px-4 py-2 text-xs tracking-[0.2em] text-[color:var(--color-body)] uppercase hover:text-[color:var(--color-gold)]"
              >
                Start over
              </button>
            </div>
            {scene !== "asis" && !edited && plate?.kind === "photo" ? (
              /*
               * The arrangement, in the phase where the picture is made. It used to sit beside the four
               * downloads, which asked the same question twice — once inside a billboard's 8:3 mount and
               * again inside a venue card's 3:4 — and made an arrangement that looked right in one surface
               * look wrong in the next. Here it is a decision about the picture, judged in the picture's own
               * frame, and the city receives it already made.
               */
              <Arrange
                artworkUrl={plate.groundUrl ?? image}
                subjectUrl={plate.subjectUrl}
                copy={payoff.copy}
                fit={payoff.fit}
                layer={payoff.layer}
                setLayer={payoff.setLayer}
                onToCity={toCity}
              />
            ) : null}

            {!edited ? (
              /*
               * On a phone the way out of this phase was 668px of scrolling below the fold, under an editor
               * that is a 1024px desktop surface. The arrangement and the city are the product; the editor is
               * optional and desktop-shaped. So the door rides with the visitor.
               */
              <div
                className="sticky bottom-3 z-10 mb-5 flex items-center gap-3 rounded-[2px] border p-2 sm:hidden"
                style={{
                  background: "color-mix(in srgb, var(--color-ink) 86%, transparent)",
                  borderColor: "var(--color-rule)",
                  backdropFilter: "blur(8px)",
                }}
              >
                <button type="button" data-testid="phone-to-city" onClick={toCity} className="btn w-full">
                  Take it into the city
                </button>
              </div>
            ) : null}

            <p className="mb-5 max-w-[62ch] text-sm leading-relaxed text-[color:var(--color-muted)]">
              Brief: {plan.brief}.
              {meta?.location ? <span> Printed at the {meta.location}.</span> : null}
              {plate?.kind === "plate" ? <span> (Using a cast plate.)</span> : null}
            </p>
            {source && image ? <BeforeAfter before={source} after={image} /> : null}
            {image ? (
              <div className="mt-5 flex flex-wrap items-center gap-3">
                <a
                  href={image}
                  download={frameName}
                  data-testid="download-frame"
                  className="lift border px-5 py-3 text-xs tracking-[0.2em] uppercase"
                  style={{ background: "var(--color-gold)", color: "var(--color-ink)", borderColor: "var(--color-gold)" }}
                >
                  Download this frame
                </a>
                <span className="kicker" style={{ color: "var(--color-muted)" }}>
                  clean PNG · no text, no watermark
                </span>
                {cut ? (
                  <span
                    className="kicker"
                    style={{ color: "var(--color-muted)" }}
                    data-testid="cut-source"
                  >
                    {cut.cutSource === "model"
                      ? `found by the segmenter (${Math.round(cut.share * 100)}% of the frame)`
                      : cut.cutSource === "classic"
                        ? "rough find — the segmenter could not load"
                        : "whole frame painted"}
                  </span>
                ) : null}
              </div>
            ) : null}
            <details
              data-testid="editor-disclosure"
              open={editorOpen}
              onToggle={(event) =>
                setEditorOpen((event.currentTarget as HTMLDetailsElement).open)
              }
              className="rule border-t pt-4"
            >
              <summary className="lift cursor-pointer text-xs tracking-[0.2em] uppercase" style={{ color: "var(--color-body)" }}>
                the editor — text, stickers, filters
                <span className="ml-2 normal-case tracking-normal" style={{ color: "var(--color-muted)" }}>
                  (a desktop tool; it is cramped on a phone — the arrangement and the city below are not)
                </span>
              </summary>
              <div className="mt-4">
                <EditorSurface surfaceId={plan.surfaceId} image={arrangedPlate ?? image} gating={plan.gating} onSaved={onSaved} />
              </div>
            </details>
          </motion.section>
        ) : null}

        {stage === "city" && saved ? (
          <motion.div
            initial={reduce ? undefined : { opacity: 0, y: 14 }}
            animate={reduce ? undefined : { opacity: 1, y: 0 }}
            transition={{ duration: 0.5, ease: EASE }}
            className="mt-10"
          >
            <Launch
              /* An edit is one flat picture: the layers are gone into it, so it *is* the artwork. */
              artworkUrl={edited ? saved : plate?.kind === "photo" ? plate.groundUrl ?? saved : saved}
              subjectUrl={edited ? undefined : plate?.kind === "photo" ? plate.subjectUrl : undefined}
              // The city's plates are arranged; "as it is" is their own room, and they stand where they stood.
              arranging={scene !== "asis" && !edited}
              copy={payoff.copy}
              setCopy={payoff.setCopy}
              fit={payoff.fit}
              setFit={payoff.setFit}
              layer={payoff.layer}
              placementId={payoff.placementId}
              setPlacementId={payoff.setPlacementId}
              onBack={() => setStage(viaEditor ? "editing" : "printed")}
              backLabel={viaEditor ? "Back to the editor" : "Back to your plate"}
            />

            {/* Their own three artefacts, walked by scroll: the photograph, the plate, the place. */}
            {source && image ? (
              <StoryScroll images={{ photograph: source, plate: image, city: sceneSrc(scene) }} />
            ) : null}
          </motion.div>
        ) : null}
        </div>
      </main>

      <footer className="rule mx-auto mt-16 max-w-[1280px] border-t px-4 py-8 sm:px-8">
        <p className="kicker">Bahía Rosa · la gaviota</p>
        <p className="mt-3 max-w-[70ch] text-xs leading-relaxed text-[color:var(--color-faint)]">
          Unofficial fan-made project for the Unlayer Build with React Image Editor Challenge. Not
          affiliated with, endorsed by, or connected to Rockstar Games or Take-Two Interactive. All
          visuals are original work; the city (Bahía Rosa), its newspaper (LA GAVIOTA) and every
          placement it publishes into are invented. The print desk runs on your own machine: no
          account, no API key, and nothing you upload leaves it.
        </p>
      </footer>
    </div>
  );
}
